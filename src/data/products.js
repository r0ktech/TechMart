export const getProductById = (id) => products.find(p => p.id === id);

export const getProductsByCategory = (category) => products.filter(p => p.category === category);

export const getFeaturedProducts = () => products.filter(p => p.featured);

export const getTrendingProducts = () => products.filter(p => p.trending);

export const getDealProducts = () => products.filter(p => p.deal);

export const searchProducts = (query) => {
  const q = query.toLowerCase();
  return products.filter(p =>
    p.name.toLowerCase().includes(q) ||
    p.brand.toLowerCase().includes(q) ||
    p.category.toLowerCase().includes(q) ||
    p.description.toLowerCase().includes(q) ||
    p.tags.some(t => t.includes(q))
  );
};

export const getBrands = () => [...new Set(products.map(p => p.brand))];

export const getCategories = () => [...new Set(products.map(p => p.category))];
